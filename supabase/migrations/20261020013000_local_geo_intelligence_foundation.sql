create or replace function public.sync_geo_place_location()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.lat is not null and new.lng is not null then
    new.location := extensions.st_setsrid(extensions.st_makepoint(new.lng, new.lat), 4326)::extensions.geography;
  else
    new.location := null;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_geo_places_sync_location on public.geo_places;
create trigger trg_geo_places_sync_location
before insert or update of lat,lng on public.geo_places
for each row execute function public.sync_geo_place_location();

revoke all on function public.sync_geo_place_location() from public, anon, authenticated;

create or replace function public.geo_nearest_place(
  p_lat double precision,
  p_lng double precision,
  p_country_code text default null,
  p_limit integer default 10
)
returns table (
  id uuid,
  canonical_code text,
  country_code text,
  name_ar text,
  name_en text,
  place_type text,
  lat double precision,
  lng double precision,
  distance_m double precision,
  confidence smallint
)
language sql
stable
set search_path = ''
as $$
  select
    p.id,
    p.canonical_code,
    p.country_code,
    p.name_ar,
    p.name_en,
    p.place_type,
    p.lat,
    p.lng,
    extensions.st_distance(
      p.location,
      extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography
    ) as distance_m,
    p.confidence
  from public.geo_places p
  where p.is_active = true
    and p.location is not null
    and (p_country_code is null or p.country_code = upper(p_country_code))
  order by p.location operator(extensions.<->)
    extensions.st_setsrid(extensions.st_makepoint(p_lng, p_lat), 4326)::extensions.geography
  limit least(greatest(coalesce(p_limit, 10), 1), 50);
$$;

revoke all on function public.geo_nearest_place(double precision,double precision,text,integer)
  from public, anon, authenticated;
grant execute on function public.geo_nearest_place(double precision,double precision,text,integer)
