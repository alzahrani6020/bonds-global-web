insert into public.geo_places (
  canonical_code,country_code,name_ar,name_en,canonical_name,place_type,
  lat,lng,population,elevation_m,source_code,source_id,confidence,metadata
)
select
  c.code,
  c.country_code,
  c.name_ar,
  c.name_en,
  coalesce(c.name_ar,c.name_en,c.code),
  case
    when c.locality_type in ('city','town','village','hijra','hamlet','oasis','district','settlement')
      then c.locality_type
    else 'other'
  end,
  c.lat,
  c.lng,
  nullif(c.population,0),
  null,
  'bonds_legacy',
  c.id::text,
  case
    when c.lat is not null and c.lng is not null and c.name_ar is not null and c.name_en is not null then 80
    when c.lat is not null and c.lng is not null then 70
    else 55
  end,
  jsonb_build_object(
    'legacy_city_id',c.id,
    'legacy_region',c.region,
    'legacy_admin_level_2',c.admin_level_2,
    'legacy_city_types',coalesce(c.city_types,'{}'::text[])
  )
from public.cities c
where c.code is not null
on conflict (canonical_code) do update set
  country_code=excluded.country_code,
  name_ar=excluded.name_ar,
  name_en=excluded.name_en,
  canonical_name=excluded.canonical_name,
  place_type=excluded.place_type,
  lat=excluded.lat,
  lng=excluded.lng,
  population=excluded.population,
  source_code=excluded.source_code,
  source_id=excluded.source_id,
  confidence=greatest(public.geo_places.confidence,excluded.confidence),
  metadata=public.geo_places.metadata || excluded.metadata,
  updated_at=now();

insert into public.geo_place_features (
  place_id,population,purchasing_power_index,data_confidence_score,dataset_version,provenance
)
select
  gp.id,
  nullif(c.population,0),
  c.purchasing_power_index,
  case
    when c.population is not null and c.population > 0 and c.purchasing_power_index is not null then 65
    when c.population is not null and c.population > 0 then 55
    else 30
  end,
  'legacy-bootstrap-1',
  jsonb_build_object(
    'population','cities.population',
    'purchasing_power_index','cities.purchasing_power_index'
  )
from public.cities c
join public.geo_places gp on gp.canonical_code = c.code
on conflict (place_id) do update set
  population=coalesce(excluded.population,public.geo_place_features.population),
  purchasing_power_index=coalesce(excluded.purchasing_power_index,public.geo_place_features.purchasing_power_index),
  data_confidence_score=greatest(public.geo_place_features.data_confidence_score,excluded.data_confidence_score),
  dataset_version=excluded.dataset_version,
  provenance=public.geo_place_features.provenance || excluded.provenance,
  updated_at=now();

