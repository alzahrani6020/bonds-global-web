-- Durable Assistant Notifications.
-- Server-side persistence only; browser clients cannot read/write this table directly.

CREATE TABLE IF NOT EXISTS public.assistant_notifications (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  notification_id text NOT NULL,
  event_id text NOT NULL,
  event_type text NOT NULL,
  workflow_key text,
  boundary text NOT NULL,
  resource_id text,
  priority text NOT NULL DEFAULT 'medium'
    CHECK (priority IN ('low','medium','high','critical')),
  title_ar text,
  title_en text,
  message_ar text,
  message_en text,
  action jsonb,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, notification_id),
  CHECK (char_length(notification_id) BETWEEN 1 AND 160),
  CHECK (char_length(event_id) BETWEEN 1 AND 160),
  CHECK (char_length(boundary) BETWEEN 1 AND 500)
);

CREATE INDEX IF NOT EXISTS idx_assistant_notifications_user_unread
  ON public.assistant_notifications (user_id, read_at, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_assistant_notifications_workflow
  ON public.assistant_notifications (user_id, workflow_key, created_at DESC);

ALTER TABLE public.assistant_notifications ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.assistant_notifications FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE ON public.assistant_notifications TO service_role;

COMMENT ON TABLE public.assistant_notifications IS
  'Durable user-scoped notifications generated by BONDS Assistant events. Server API only; no direct browser access.';
