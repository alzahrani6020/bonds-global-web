-- Bonds Global — governed geo ingestion architecture
-- Separates immutable raw ingestion from canonical geography promotion.

begin;

create schema if not exists geo_ingest;
revoke all on schema geo_ingest from public, anon, authenticated;
grant usage on schema geo_ingest to service_role;

create table if not exists geo_ingest.source_snapshots (
  id uuid primary key default gen_random_uuid(),
  source_code text not null references public.geo_data_sources(code) on delete restrict,
  dataset_version text not null,
  checksum_sha256 text,
  source_uri text,
  published_at timestamptz,
  acquired_at timestamptz not null default now(),
  status text not null default 'ready' check (status in ('ready','staged','validated','promoted','rejected','superseded')),
  metadata jsonb not null default '{}'::jsonb,
  unique(source_code,dataset_version,checksum_sha256)
);

create table if not exists geo_ingest.runs (
  id uuid primary key default gen_random_uuid(),
  snapshot_id uuid not null references geo_ingest.source_snapshots(id) on delete restrict,
  country_code text,
  stage text not null default 'staging' check (stage in ('staging','validation','matching','promotion','complete')),
  status text not null default 'running' check (status in ('running','passed','failed','blocked','cancelled')),
  raw_count bigint not null default 0,
  valid_count bigint not null default 0,
  rejected_count bigint not null default 0,
  matched_count bigint not null default 0,
  new_count bigint not null default 0,
  review_count bigint not null default 0,
  metrics jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table if not exists geo_ingest.raw_places (
  id bigint generated by default as identity primary key,
  run_id uuid not null references geo_ingest.runs(id) on delete cascade,
  source_code text not null references public.geo_data_sources(code) on delete restrict,
  source_id text not null,
  country_code text not null,
  name_ar text,
  name_en text,
  normalized_name_ar text,
  normalized_name_en text,
  place_type text,
  admin1_code text,
  admin2_code text,
  admin3_code text,
  admin4_code text,
  lat double precision check (lat is null or lat between -90 and 90),
  lng double precision check (lng is null or lng between -180 and 180),
  location extensions.geography(Point,4326),
  population bigint check (population is null or population >= 0),
  elevation_m numeric,
  source_updated_at timestamptz,
  aliases jsonb not null default '[]'::jsonb,
  raw_payload jsonb not null default '{}'::jsonb,
  validation_status text not null default 'pending' check (validation_status in ('pending','valid','invalid')),
  validation_errors jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  unique(run_id,source_code,source_id)
);

create table if not exists geo_ingest.match_candidates (
  id bigint generated by default as identity primary key,
  run_id uuid not null references geo_ingest.runs(id) on delete cascade,
  raw_place_id bigint not null references geo_ingest.raw_places(id) on delete cascade,
  canonical_place_id uuid references public.geo_places(id) on delete cascade,
  match_type text not null check (match_type in ('source_identity','exact_name','name_and_distance','new_place','ambiguous')),
  name_score numeric check (name_score is null or name_score between 0 and 100),
  distance_m numeric,
  admin_score numeric check (admin_score is null or admin_score between 0 and 100),
  overall_score numeric not null check (overall_score between 0 and 100),
  decision text not null default 'review' check (decision in ('auto_match','new_canonical','review','reject')),
  reason jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(raw_place_id,canonical_place_id,match_type)
);

create table if not exists geo_ingest.quality_results (
  id bigint generated by default as identity primary key,
  run_id uuid not null references geo_ingest.runs(id) on delete cascade,
  rule_code text not null,
  severity text not null check (severity in ('info','warning','error','blocker')),
  passed boolean not null,
  actual_value numeric,
  threshold_value numeric,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(run_id,rule_code)
);

create table if not exists public.geo_place_source_links (
  id bigint generated by default as identity primary key,
  place_id uuid not null references public.geo_places(id) on delete cascade,
  source_code text not null references public.geo_data_sources(code) on delete restrict,
  source_id text not null,
  source_updated_at timestamptz,
  confidence smallint not null default 50 check (confidence between 0 and 100),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(source_code,source_id),
  unique(place_id,source_code,source_id)
);

create index if not exists idx_geo_place_source_links_place
  on public.geo_place_source_links(place_id);

alter table public.geo_place_source_links enable row level security;
revoke all on public.geo_place_source_links from anon, authenticated;
grant select,insert,update,delete on public.geo_place_source_links to service_role;

create table if not exists geo_ingest.promotions (
  id bigint generated by default as identity primary key,
  run_id uuid not null references geo_ingest.runs(id) on delete restrict,
  raw_place_id bigint not null references geo_ingest.raw_places(id) on delete restrict,
  canonical_place_id uuid not null references public.geo_places(id) on delete restrict,
  action text not null check (action in ('matched_existing','created_canonical','updated_canonical')),
  decision_score numeric,
  reason jsonb not null default '{}'::jsonb,
  promoted_at timestamptz not null default now(),
  unique(run_id,raw_place_id)
);

create index if not exists idx_geo_ingest_runs_snapshot on geo_ingest.runs(snapshot_id);
create index if not exists idx_geo_ingest_raw_run_country on geo_ingest.raw_places(run_id,country_code);
create index if not exists idx_geo_ingest_raw_source on geo_ingest.raw_places(source_code,source_id);
create index if not exists idx_geo_ingest_raw_location on geo_ingest.raw_places using gist(location);
create index if not exists idx_geo_ingest_raw_name_ar on geo_ingest.raw_places(normalized_name_ar);
create index if not exists idx_geo_ingest_raw_name_en on geo_ingest.raw_places(normalized_name_en);
create index if not exists idx_geo_ingest_candidates_run_decision on geo_ingest.match_candidates(run_id,decision);
create index if not exists idx_geo_ingest_candidates_raw on geo_ingest.match_candidates(raw_place_id);
create index if not exists idx_geo_ingest_quality_run on geo_ingest.quality_results(run_id);

create or replace function geo_ingest.sync_raw_place_location()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.lat is not null and new.lng is not null then
    new.location := extensions.st_setsrid(extensions.st_makepoint(new.lng,new.lat),4326)::extensions.geography;
  else
    new.location := null;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_geo_ingest_raw_location on geo_ingest.raw_places;
create trigger trg_geo_ingest_raw_location
before insert or update of lat,lng on geo_ingest.raw_places
for each row execute function geo_ingest.sync_raw_place_location();

create or replace function geo_ingest.refresh_run_metrics(p_run_id uuid)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_metrics jsonb;
begin
  select jsonb_build_object(
    'raw_count', count(*),
    'valid_count', count(*) filter (where validation_status='valid'),
    'invalid_count', count(*) filter (where validation_status='invalid'),
    'coordinate_coverage',
      case when count(*)=0 then 0
           else round((count(*) filter (where location is not null))::numeric / count(*)::numeric, 6)
      end,
    'arabic_name_coverage',
      case when count(*)=0 then 0
           else round((count(*) filter (where name_ar is not null and btrim(name_ar)<>''))::numeric / count(*)::numeric, 6)
      end,
    'duplicate_source_identity_count',
      (select count(*) from (
        select source_code,source_id
        from geo_ingest.raw_places
        where run_id=p_run_id
        group by source_code,source_id
        having count(*)>1
      ) d)
  )
  into v_metrics
  from geo_ingest.raw_places
  where run_id=p_run_id;

  update geo_ingest.runs
  set raw_count=coalesce((v_metrics->>'raw_count')::bigint,0),
      valid_count=coalesce((v_metrics->>'valid_count')::bigint,0),
      rejected_count=coalesce((v_metrics->>'invalid_count')::bigint,0),
      metrics=v_metrics
  where id=p_run_id;

  return v_metrics;
end;
$$;

create or replace function geo_ingest.evaluate_quality_gates(p_run_id uuid)
returns table(rule_code text,severity text,passed boolean,actual_value numeric,threshold_value numeric)
language plpgsql
set search_path = ''
as $$
declare
  v_metrics jsonb;
  v_raw numeric;
  v_coords numeric;
  v_dupes numeric;
begin
  v_metrics := geo_ingest.refresh_run_metrics(p_run_id);
  v_raw := coalesce((v_metrics->>'raw_count')::numeric,0);
  v_coords := coalesce((v_metrics->>'coordinate_coverage')::numeric,0);
  v_dupes := coalesce((v_metrics->>'duplicate_source_identity_count')::numeric,0);

  delete from geo_ingest.quality_results where run_id=p_run_id;

  insert into geo_ingest.quality_results(run_id,rule_code,severity,passed,actual_value,threshold_value,detail)
  values
    (p_run_id,'non_empty_dataset','blocker',v_raw>0,v_raw,1,'{}'::jsonb),
    (p_run_id,'coordinate_coverage','blocker',v_coords>=0.95,v_coords,0.95,'{}'::jsonb),
    (p_run_id,'unique_source_identity','blocker',v_dupes=0,v_dupes,0,'{}'::jsonb);

  return query
  select q.rule_code,q.severity,q.passed,q.actual_value,q.threshold_value
  from geo_ingest.quality_results q
  where q.run_id=p_run_id
  order by q.severity desc,q.rule_code;
end;
$$;

