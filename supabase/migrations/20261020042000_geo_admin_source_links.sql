-- Bonds Global — provider-independent administrative source identity.
-- Keeps canonical ADM1 independent from GeoNames or any future provider.

begin;

create table if not exists public.geo_admin_area_source_links (
  id bigint generated by default as identity primary key,
  admin_area_id uuid not null references public.geo_admin_areas(id) on delete cascade,
  source_code text not null references public.geo_data_sources(code) on delete restrict,
  country_code text not null,
  admin_level smallint not null check (admin_level between 0 and 6),
  source_admin_code text not null,
  source_id text,
  source_updated_at timestamptz,
  confidence smallint not null default 50 check (confidence between 0 and 100),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(source_code,country_code,admin_level,source_admin_code),
  unique(source_code,source_id)
);

create index if not exists idx_geo_admin_source_links_area
  on public.geo_admin_area_source_links(admin_area_id);
create index if not exists idx_geo_admin_source_links_lookup
  on public.geo_admin_area_source_links(source_code,country_code,admin_level,source_admin_code);

alter table public.geo_admin_area_source_links enable row level security;
revoke all on public.geo_admin_area_source_links from anon,authenticated;
grant select,insert,update,delete on public.geo_admin_area_source_links to service_role;
grant usage,select on sequence public.geo_admin_area_source_links_id_seq to service_role;

create or replace function public.dq_find_geo_admin_source_links()
returns bigint
language plpgsql
security definer
set search_path to 'public','auth'
as $func$
declare
  v_count bigint := 0;
begin
  insert into public.data_quality_issues(
    check_type,entity_type,entity_id,field_name,severity,message,metadata
  )
  select
    'geo_integrity','geo_admin_area',ga.id,'source_link','medium',
    'المستوى الإداري canonical لا يحتوي هوية مصدر GeoNames معتمدة',
    jsonb_build_object(
      'country_code',ga.country_code,
      'canonical_code',ga.canonical_code,
      'admin_level',ga.admin_level
    )
  from public.geo_admin_areas ga
  where ga.is_active=true
    and ga.admin_level=1
    and not exists (
      select 1
      from public.geo_admin_area_source_links l
      where l.admin_area_id=ga.id
        and l.source_code='geonames_dump'
        and l.admin_level=1
    );

  get diagnostics v_count = row_count;
  return v_count;
end;
$func$;

revoke all on function public.dq_find_geo_admin_source_links() from public,anon,authenticated;
grant execute on function public.dq_find_geo_admin_source_links() to service_role;

commit;
