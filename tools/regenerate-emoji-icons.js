const fs = require('fs');
const path = require('path');
const https = require('https');
const emojiRegex = require('emoji-regex');

const ROOT = path.join(__dirname, '..');
const EXTS = new Set(['.html', '.js', '.css', '.json', '.md', '.txt', '.sql', '.yml', '.yaml']);
const EMOJI_RE = emojiRegex();

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') && entry.name !== '.github') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', '.git', '.vercel', '.tmp-pdf', '.githooks'].includes(entry.name)) continue;
      walk(full, files);
    } else if (EXTS.has(path.extname(entry.name).toLowerCase())) {
      files.push(full);
    }
  }
  return files;
}

function collectEmojis() {
  const files = walk(ROOT);
  const set = new Set();
  for (const f of files) {
    let text;
    try {
      text = fs.readFileSync(f, 'utf8');
    } catch (e) { continue; }
    let m;
    EMOJI_RE.lastIndex = 0;
    while ((m = EMOJI_RE.exec(text)) !== null) {
      set.add(m[0]);
    }
  }
  return Array.from(set);
}

function toCodepoints(emoji) {
  const pts = [];
  for (const cp of emoji) {
    const cpv = cp.codePointAt(0);
    if (cpv === 0xfe0f) continue; // Twemoji URLs omit the emoji variation selector
    pts.push(cpv.toString(16).toLowerCase());
  }
  return pts.join('-');
}

function fetchSvg(codepoints) {
  const url = `https://cdn.jsdelivr.net/gh/twitter/twemoji@latest/assets/svg/${codepoints}.svg`;
  return new Promise((resolve, reject) => {
    https.get(url, { timeout: 15000 }, (res) => {
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error(`HTTP ${res.statusCode}`));
        return;
      }
      let data = '';
      res.setEncoding('utf8');
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve(data));
    }).on('error', reject);
  });
}

async function runWithConcurrency(items, fn, concurrency = 10) {
  const results = [];
  let i = 0;
  async function worker() {
    while (i < items.length) {
      const idx = i++;
      try {
        results[idx] = await fn(items[idx]);
      } catch (e) {
        results[idx] = { error: e };
      }
    }
  }
  const workers = Array.from({ length: concurrency }, () => worker());
  await Promise.all(workers);
  return results;
}

async function main() {
  const emojis = collectEmojis();
  console.log(`Found ${emojis.length} unique emoji sequences`);

  const results = await runWithConcurrency(emojis, async (emoji) => {
    const cps = toCodepoints(emoji);
    const svg = await fetchSvg(cps);
    return { emoji, svg, cps };
  }, 10);

  const entries = [];
  let failed = 0;
  for (let i = 0; i < emojis.length; i++) {
    const r = results[i];
    if (r.error) {
      failed++;
      console.error('✗', emojis[i], r.error.message);
      continue;
    }
    const escaped = r.svg.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '');
    entries.push(`  "${r.emoji}": "${escaped}"`);
    console.log('✓', r.emoji, r.cps);
  }

  const header = `/**
 * Emoji-to-SVG mapping using Twemoji graphics (CC-BY 4.0).
 * Twemoji by Twitter / X is licensed under CC-BY 4.0: https://twemoji.twitter.com/
 * Fallback symbols are custom SVG using currentColor.
 * Auto-generated by tools/regenerate-emoji-icons.js
 */

const EMOJI_SVGS = {`;
  const footer = `};

const EmojiIcons = {
  get(emoji) { return EMOJI_SVGS[emoji] || null; },
  replaceInText(text) {
    if (typeof text !== 'string') return text;
    return text.replace(EMOJI_RE, emoji => EMOJI_SVGS[emoji] || emoji);
  }
};

if (typeof window !== 'undefined') window.EmojiIcons = EmojiIcons;
if (typeof module !== 'undefined' && module.exports) module.exports = EmojiIcons;
`;

  const out = header + '\n' + entries.join(',\n') + '\n};\n' + footer;
  fs.writeFileSync(path.join(ROOT, 'components/emoji-icons.js'), out, 'utf8');
  console.log(`\nWrote components/emoji-icons.js with ${entries.length} entries (${failed} failed)`);
}

main().catch(e => { console.error(e); process.exit(1); });
