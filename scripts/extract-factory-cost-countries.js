const fs = require('fs');
const path = require('path');

const baseDir = path.resolve(__dirname, '..');
const patterns = [
  { dir: path.join(baseDir, 'calculators'), lang: 'ar' },
  { dir: path.join(baseDir, 'en', 'calculators'), lang: 'en' }
];

const result = { ar: {}, en: {} };

function evalObjectLiteral(text) {
  // Wrap in parentheses so it parses as an expression
  const fn = new Function('return (' + text + ')');
  return fn();
}

function extractInitConfig(content) {
  const marker = 'FactoryCostCalculator.init({';
  const idx = content.indexOf(marker);
  if (idx === -1) return null;
  let start = idx + marker.length - 1; // position of '{'
  let depth = 0;
  let end = start;
  for (let i = start; i < content.length; i++) {
    const ch = content[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) { end = i + 1; break; }
    }
  }
  // Find closing ');' after object
  const after = content.slice(end);
  const m = after.match(/^\s*\)\s*;?/);
  if (!m) {
    console.warn('Could not find closing ); after object');
  }
  const literal = content.slice(start, end);
  return evalObjectLiteral(literal);
}

function extractSaConfig(content, lang) {
  // Extract currencies/gosi/etc via regex from main factory-cost.html
  const config = {
    countryCode: 'SA',
    lang,
    locale: lang === 'en' ? 'en-SA' : 'ar-SA',
    currency: 'SAR',
    gosiRate: 0.12,
    gosiExpatRate: 0.02,
    expatFeePerWorker: 800,
    cities: {}
  };
  // Extract cities object: e.g. riyadh: { rent: 220, name: 'الرياض' }
  // Main factory-cost.html uses `cityRates`.
  const citiesMatch = content.match(/(?:const|let|var)\s+(?:cities|cityRates)\s*=\s*(\{[\s\S]*?\n\s*\})/);
  if (citiesMatch) {
    config.cities = evalObjectLiteral(citiesMatch[1]);
  }
  // Override numeric values from inline script if present
  const gosiLocalMatch = content.match(/gosiSaudi\s*=\s*saudiPayroll\s*\*\s*([0-9.]+)/);
  if (gosiLocalMatch) config.gosiRate = parseFloat(gosiLocalMatch[1]);
  const gosiExpatMatch = content.match(/gosiExpat\s*=\s*expatPayroll\s*\*\s*([0-9.]+)/);
  if (gosiExpatMatch) config.gosiExpatRate = parseFloat(gosiExpatMatch[1]);
  const expatFeeMatch = content.match(/expatFees\s*=\s*expatWorkers\s*\*\s*([0-9.]+)/);
  if (expatFeeMatch) config.expatFeePerWorker = parseFloat(expatFeeMatch[1]);
  const currencyMatch = content.match(/(['"])SAR\1/) || content.match(/ر\.س/) || content.match(/SAR/);
  config.currency = 'SAR';
  return config;
}

patterns.forEach(({ dir, lang }) => {
  const files = fs.readdirSync(dir).filter(f => f.startsWith('factory-cost-') && f.endsWith('.html'));
  files.forEach(f => {
    const code = f.replace('factory-cost-', '').replace('.html', '').toUpperCase();
    const content = fs.readFileSync(path.join(dir, f), 'utf8');
    const config = extractInitConfig(content);
    if (config) {
      result[lang][code] = config;
    } else {
      console.warn('No init config in', f);
    }
  });
  // Main factory-cost.html as SA
  const mainFile = path.join(dir, 'factory-cost.html');
  if (fs.existsSync(mainFile)) {
    const content = fs.readFileSync(mainFile, 'utf8');
    result[lang]['SA'] = extractSaConfig(content, lang);
  }
});

const outPath = path.join(baseDir, 'calculators', 'factory-cost-countries.js');
const out = `// Auto-generated by scripts/extract-factory-cost-countries.js
window.FactoryCostCountries = ${JSON.stringify(result, null, 2)};
`;
fs.writeFileSync(outPath, out, 'utf8');
console.log('Wrote', outPath);
