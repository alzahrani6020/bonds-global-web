 count(*) as candidate_rows,
 count(*) filter (where admin_area_exists) as valid_admin_areas,
 count(*) filter (where not admin_area_exists) as missing_admin_areas,
 count(*) filter (where admin_code_collision) as admin_code_collisions,
 count(*) filter (where source_id_collision) as source_id_collisions,
 count(distinct source_admin_code) as distinct_source_admin_codes,
 count(distinct source_id) as distinct_source_ids
from checks;
