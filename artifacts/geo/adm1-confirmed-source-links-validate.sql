checks as (
 select c.*,
   a.canonical_code,
   a.name_en,
   (a.id is not null) as admin_area_exists,
   exists(select 1 from public.geo_admin_area_source_links l where l.source_code=c.source_code and l.country_code=c.country_code and l.admin_level=c.admin_level and l.source_admin_code=c.source_admin_code) as admin_code_collision,
   exists(select 1 from public.geo_admin_area_source_links l where l.source_code=c.source_code and l.source_id=c.source_id) as source_id_collision
 from candidate c
 left join public.geo_admin_areas a on a.id=c.admin_area_id and a.admin_level=1 and a.country_code=c.country_code
)
