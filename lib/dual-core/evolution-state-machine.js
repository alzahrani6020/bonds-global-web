'use strict';

const STATES = Object.freeze({
  APPROVED_TARGET: 'APPROVED_TARGET',
  ENGINEERING: 'ENGINEERING',
  REPAIRING: 'REPAIRING',
  VALIDATING: 'VALIDATING',
  WAITING_FOR_CAPACITY: 'WAITING_FOR_CAPACITY',
  REBASING: 'REBASING',
  REVALIDATING: 'REVALIDATING',
  STAGING: 'STAGING',
  INTEGRATION_VERIFIED: 'INTEGRATION_VERIFIED',
  MERGE_READY: 'MERGE_READY',
  MERGED: 'MERGED',
  PRODUCTION: 'PRODUCTION',
  VERIFIED: 'VERIFIED',
  BLOCKED: 'BLOCKED',
  PAUSED: 'PAUSED',
  ROLLED_BACK: 'ROLLED_BACK'
});

const TRANSITIONS = Object.freeze({
  [STATES.APPROVED_TARGET]: new Set([STATES.ENGINEERING, STATES.WAITING_FOR_CAPACITY, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.ENGINEERING]: new Set([STATES.REPAIRING, STATES.VALIDATING, STATES.WAITING_FOR_CAPACITY, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.REPAIRING]: new Set([STATES.REPAIRING, STATES.VALIDATING, STATES.WAITING_FOR_CAPACITY, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.VALIDATING]: new Set([STATES.REPAIRING, STATES.REBASING, STATES.WAITING_FOR_CAPACITY, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.WAITING_FOR_CAPACITY]: new Set([STATES.ENGINEERING, STATES.REPAIRING, STATES.VALIDATING, STATES.REBASING, STATES.REVALIDATING, STATES.PAUSED, STATES.BLOCKED]),
  [STATES.REBASING]: new Set([STATES.REVALIDATING, STATES.REPAIRING, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.REVALIDATING]: new Set([STATES.REPAIRING, STATES.STAGING, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.STAGING]: new Set([STATES.INTEGRATION_VERIFIED, STATES.REPAIRING, STATES.BLOCKED, STATES.PAUSED]),
  [STATES.INTEGRATION_VERIFIED]: new Set([STATES.MERGE_READY, STATES.REPAIRING, STATES.BLOCKED]),
  [STATES.MERGE_READY]: new Set([STATES.MERGED, STATES.REPAIRING, STATES.BLOCKED]),
  [STATES.MERGED]: new Set([STATES.PRODUCTION, STATES.ROLLED_BACK, STATES.BLOCKED]),
  [STATES.PRODUCTION]: new Set([STATES.VERIFIED, STATES.ROLLED_BACK, STATES.REPAIRING, STATES.BLOCKED]),
  [STATES.VERIFIED]: new Set([]),
  [STATES.BLOCKED]: new Set([STATES.APPROVED_TARGET, STATES.ENGINEERING, STATES.REPAIRING, STATES.PAUSED]),
  [STATES.PAUSED]: new Set([STATES.APPROVED_TARGET, STATES.ENGINEERING, STATES.REPAIRING, STATES.VALIDATING, STATES.WAITING_FOR_CAPACITY]),
  [STATES.ROLLED_BACK]: new Set([STATES.REPAIRING, STATES.BLOCKED])
});

function canTransition(from, to) {
  return Boolean(TRANSITIONS[from]?.has(to));
}

function transition(state, to, context = {}) {
  if (!STATES[to]) throw new Error('EVOLUTION_STATE_UNKNOWN');
  if (!canTransition(state.current, to)) throw new Error('EVOLUTION_TRANSITION_INVALID');
  return {
    ...state,
    current: to,
    previous: state.current,
    updated_at: new Date().toISOString(),
    reason: context.reason || null,
    checkpoint_required: Boolean(context.checkpoint_required)
  };
}

function createEvolutionState(targetId) {
  if (!targetId) throw new Error('EVOLUTION_TARGET_REQUIRED');
  return {
    target_id: String(targetId),
    current: STATES.APPROVED_TARGET,
    previous: null,
    updated_at: new Date().toISOString(),
    reason: null,
    checkpoint_required: true
  };
}

module.exports = { STATES, TRANSITIONS, canTransition, transition, createEvolutionState };
